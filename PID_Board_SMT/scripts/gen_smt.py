    t = sh.place(*DPOT_SYM, ref, DPOT_VAL, FP["TSSOP20"], x, y, 0, 5,
                 ref_xy=(x + 11.43, y - 11.43), val_xy=(x + 11.43, y + 11.43), just="left")
