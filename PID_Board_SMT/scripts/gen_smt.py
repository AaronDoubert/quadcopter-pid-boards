def decouple(sh, x, y, cref, val, fp=None, kind="C"):
    top, bot, nums = sh.two(kind, cref, val, fp or FP["C0603"], x, y, horizontal=False)
    sh.pwr("+5V", *top)
    sh.pwr("GND", *bot)
    sh.expect("+5V", f"{cref}.1"); sh.expect("GND", f"{cref}.2")


