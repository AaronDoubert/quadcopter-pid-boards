def lcsc(value, fp):
    if fp == FP["R"]:
        return LCSC_R.get(value.split()[0])
    return LCSC.get(value)

def U():
    return str(uuid.uuid4())

def fmt(v):
    v = round(v, 2)
    return str(int(v)) if v == int(v) else str(v)

def block_at(s, i):
    d = 0
    for k in range(i, len(s)):
        if s[k] == "(":
            d += 1
        elif s[k] == ")":
            d -= 1
            if d == 0:
                return s[i:k + 1]

