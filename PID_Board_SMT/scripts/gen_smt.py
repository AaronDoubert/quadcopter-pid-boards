def main():
    sheet_ids = {}
    for name, fname, _ in SHEETS:
        m = re.search(rf'\(uuid "([^"]+)"\)\s*\(property "Sheetname" "{name}"', ROOT_TEXT)
        sheet_ids[name] = m.group(1) if m else U()
        path = os.path.join(PROJ_DIR, fname)
        if not os.path.exists(path):
            open(path, "w", encoding="utf-8", newline="\n").write(
                f'(kicad_sch\n\t(version 20260306)\n\t(generator "eeschema")\n\t(uuid "{U()}")\n)\n')

    def file_uuid(fname):
        return re.search(r'\(uuid "([^"]+)"\)', open(os.path.join(PROJ_DIR, fname), encoding="utf-8").read()).group(1)

    expected = {}
    def collect(sh, sheetname):
        for net, nodes in sh.nets.items():
            if net.startswith("~"):
                key = f"{sheetname}{net}"
            elif net in GLOBAL or net in POWER:
                key = net
            else:
                key = f"/{sheetname}/{net}" if sheetname else f"/{net}"
            expected.setdefault(key, set()).update(nodes)

    root = Sheet("PID_Board_SMT.kicad_sch", "Quad flight controller (SMT): DAC shim + analog PID", f"/{ROOT_UUID}", "0")
    root_sheet(root, sheet_ids)
    root.write(ROOT_UUID, extra_tail='\t(sheet_instances\n\t\t(path "/"\n\t\t\t(page "1")\n\t\t)\n\t)\n')
    collect(root, "")

    builds = [
        ("PID_Reference", "pid_reference.kicad_sch", "PID reference + virtual grounds", "1", lambda s: reference_sheet(s)),
        ("PID_Roll", "pid_roll.kicad_sch", "Roll axis PID", "2", lambda s: axis_sheet(s, "ROLL", 2, True, "VGND_A", "33k", True, ("U2", "U3"))),
        ("PID_Pitch", "pid_pitch.kicad_sch", "Pitch axis PID", "3", lambda s: axis_sheet(s, "PITCH", 3, True, "VGND_A", "33k", True, ("U4", "U5"))),
        ("PID_Yaw", "pid_yaw.kicad_sch", "Yaw axis PID", "4", lambda s: axis_sheet(s, "YAW", 4, False, "VGND_B", "15k", False, ("U6", "U7"))),
        ("Control_IO", "control_io.kicad_sch", "Control I/O: ESC, power, mixer", "5", lambda s: control_sheet(s)),
    ]
    for name, fname, title, pfx, fn in builds:
        sh = Sheet(fname, title, f"/{ROOT_UUID}/{sheet_ids[name]}", pfx)
        fn(sh)
        sh.write(file_uuid(fname))
        collect(sh, name)

    pro_path = os.path.join(PROJ_DIR, "PID_Board_SMT.kicad_pro")
    pro = json.load(open(pro_path, encoding="utf-8"))
    pro["sheets"] = [[ROOT_UUID, "Root"]] + [[sheet_ids[n], n] for n, _, _ in SHEETS]
    pro["meta"]["filename"] = "PID_Board_SMT.kicad_pro"
    pro["schematic"]["top_level_sheets"] = [{"filename": "PID_Board_SMT.kicad_sch", "name": "PID_Board_SMT", "uuid": ROOT_UUID}]
    pro["board"]["design_settings"]["rules"]["min_resolved_spokes"] = 1
    json.dump(pro, open(pro_path, "w", encoding="utf-8"), indent=2)
    json.dump({k: sorted(v) for k, v in expected.items()}, open(EXPECT_OUT, "w"), indent=1)
    print("generated; expected nets:", len(expected))

main()
